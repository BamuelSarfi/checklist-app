    function normalizeLanguage(language) {
        const value = String(language || '').toLowerCase();
        if (['es', 'pl', 'bn', 'ar', 'ur'].includes(value)) {
            return value;
        }
        return 'en';
    }

    function applyTextDirection(language) {
        const dir = RTL_LANGUAGES.includes(language) ? 'rtl' : 'ltr';
        document.documentElement.setAttribute('dir', dir);
        document.documentElement.setAttribute('lang', language);
    }

    function getEmployeeId() {
        try {
            const stored = sessionStorage.getItem('employeeData');
            if (!stored) {
                return null;
            }
            const parsed = JSON.parse(stored);
            return parsed?.id || null;
        } catch (_error) {
            return null;
        }
    }

    function getOverrideKey() {
        const employeeId = getEmployeeId();
        return employeeId ? `${STORAGE_KEY_PREFIX}${employeeId}` : STORAGE_KEY_PREFIX;
    }

    function getStoredOverride() {
        try {
            return sessionStorage.getItem(getOverrideKey());
        } catch (_error) {
            return null;
        }
    }

    function getAppLanguage() {
        const override = getStoredOverride();
        if (override) {
            return normalizeLanguage(override);
        }

        try {
            const stored = sessionStorage.getItem('employeeData');
            if (stored) {
                const employee = JSON.parse(stored);
                return normalizeLanguage(employee?.preferred_language || 'en');
            }
        } catch (_error) {
            // ignore
        }

        return 'en';
    }

    function setAppLanguage(language, options = {}) {
        const normalized = normalizeLanguage(language);
        const persist = options.persist !== false;

        // Always persists under getOverrideKey() (employee-scoped once logged in, a plain
        // shared key otherwise) - previously this only wrote anything when an employeeId was
        // already known, which silently no-op'd the switcher on pages reachable pre-login
        // (privacy-policy.html) since there was nowhere for the choice to land.
        if (persist) {
            try {
                sessionStorage.setItem(getOverrideKey(), normalized);
            } catch (_error) {
                // ignore
            }
        }

        return normalized;
    }

    // vars supports simple {name} substitution so each language can reorder tokens freely -
    // e.g. t('{count} of {total} required done', { count: 2, total: 5 }). Without vars this
    // behaves exactly as the plain lookup it always was.
    function t(key, vars) {
        const language = getAppLanguage();
        const normalized = normalizeLanguage(language);
        const template = normalized === 'en' ? String(key) : (TRANSLATIONS[normalized]?.[key] || String(key));

        if (!vars) {
            return template;
        }

        return template.replace(/\{(\w+)\}/g, (match, name) => (
            Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
        ));
    }

    function translateAttributes(root) {
        const nodes = (root || document).querySelectorAll('[title], [placeholder], [aria-label], [alt]');
        nodes.forEach((element) => {
            ['title', 'placeholder', 'aria-label', 'alt'].forEach((attribute) => {
                const value = element.getAttribute(attribute);
                if (!value) return;
                const translated = t(value);
                if (translated !== value) {
                    element.setAttribute(attribute, translated);
                }
            });
        });
    }

    // <option> text is deliberately skipped by translateTextNodes()'s generic walk (some
    // browsers handle text-node mutation inside <option> oddly during reflow), so option
    // labels (category pickers, checklist filters) need their own explicit pass.
    function translateOptions(root) {
        const options = (root || document).querySelectorAll('option');
        options.forEach((option) => {
            const text = option.textContent;
            if (!text || !text.trim()) return;
            const trimmed = text.trim();
            const translated = t(trimmed);
            if (translated !== trimmed) {
                option.textContent = translated;
            }
        });
    }

    function translateTextNodes(root) {
        const walker = document.createTreeWalker(root || document.body, NodeFilter.SHOW_TEXT, null);
        const nodes = [];
        let current = walker.nextNode();
        while (current) {
            nodes.push(current);
            current = walker.nextNode();
        }

        nodes.forEach((node) => {
            const parent = node.parentElement;
            if (!parent) return;
            if (['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'SELECT', 'OPTION', 'NOSCRIPT'].includes(parent.tagName)) {
                return;
            }

            const text = node.nodeValue;
            if (!text || !text.trim()) return;
            const translated = t(text.trim());
            if (translated !== text.trim()) {
                const leading = text.match(/^\s*/)?.[0] || '';
                const trailing = text.match(/\s*$/)?.[0] || '';
                node.nodeValue = `${leading}${translated}${trailing}`;
            }
        });
    }

    function translateDocument(root = document) {
        const language = getAppLanguage();
        applyTextDirection(language);

        const title = document.title;
        // t(key, vars) expects vars to be a {placeholder} substitution object, not the
        // language string - language is already read internally via getAppLanguage(). This
        // happened to be harmless (no page title currently uses a {placeholder} token), but
        // would silently fail to substitute one if a future title needed it.
        const translatedTitle = t(title);
        if (translatedTitle !== title) {
            document.title = translatedTitle;
        }

        const scope = root === document ? document.body : root;
        translateAttributes(root);
        translateTextNodes(scope);
        translateOptions(scope);

        const placeholder = root.querySelector?.('#progress_text');
        if (placeholder && placeholder.textContent && placeholder.textContent.trim() === '0 / 0 days completed') {
            placeholder.textContent = t('0 / 0 days completed', language);
        }
    }

    function refreshLanguageSelect() {
        const select = document.getElementById('language-select');
        if (select) {
            select.value = getAppLanguage();
        }
    }

    function getLanguageOptions() {
        return Object.entries(LANGUAGE_LABELS).map(([value, label]) => ({ value, label }));
    }

    window.appI18n = {
        t,
        translateDocument,
        getAppLanguage,
        setAppLanguage,
        getLanguageOptions,
        refreshLanguageSelect,
        applyTextDirection,
    };

    window.applyTranslations = translateDocument;
    window.getAppLanguage = getAppLanguage;
    window.setAppLanguage = setAppLanguage;

    window.addEventListener('DOMContentLoaded', () => {
        translateDocument(document.body);
    });
